#!/usr/bin/env python3
"""Write numbers.tex (LaTeX macros) from benchmark_report.py's summary.json.

    python docs/test_report/make_numbers.py docs/test_report/figures/summary.json

report.tex only ever quotes \\Num... macros, so rerunning the benchmark on a new
machine and these two commands regenerates the whole report.
"""

import json
import os
import sys


def fmt(v, digits=1):
    if isinstance(v, float):
        s = f"{v:,.{digits}f}"
    else:
        s = f"{v:,}"
    return s.replace(",", "\\,")


def main():
    path = sys.argv[1]
    with open(path, encoding="utf-8") as f:
        s = json.load(f)
    macros = {
        "NumGpus": s["machine"]["gpus"],
        "NumGpuModel": s["machine"]["gpu_model"],
        "NumJobsPerGpu": s["machine"]["jobs_per_gpu"],
        "NumPrice": fmt(s["price_per_hour"], 2),
        "NumPricePerGpu": fmt(s["price_per_hour"] / s["machine"]["gpus"], 2),
        "NumScenes": s["scenes"],
        "NumImages": fmt(s["images"]),
        "NumRendered": fmt(s["frames_rendered"]),
        "NumKeptPct": fmt(100 * s["kept_fraction"], 0),
        "NumAnnotations": fmt(s["annotations"]),
        "NumElapsedMin": fmt(s["elapsed_h"] * 60, 0),
        "NumImgPerHourNode": fmt(s["images_per_hour_node"], 0),
        "NumImgPerHourGpu": fmt(s["images_per_hour_per_gpu"], 0),
        "NumSecPerImageGpu": fmt(3600 / s["images_per_hour_per_gpu"], 1),
        "NumCostPerK": fmt(s["cost_per_1000_images"], 2),
        "NumSceneMedian": fmt(s["scene_wall_s"]["50"], 0),
        "NumSceneNinety": fmt(s["scene_wall_s"]["90"], 0),
        "NumRssMedian": fmt(s["peak_rss_gb"]["50"], 1),
        "NumRssMax": fmt(s["peak_rss_gb"]["100"], 1),
        "NumGpuUtil": fmt(s.get("gpu_util_mean_pct", 0.0), 0),
        "NumVramPeak": fmt(s.get("gpu_mem_peak_mib", 0) / 1024, 1),
        "NumVramTotal": fmt(s.get("gpu_mem_total_mib", 0) / 1024, 0),
        "NumHostRamPeak": fmt(s.get("host_ram_peak_gib", 0.0), 0),
        "NumHostRamTotal": fmt(s.get("host_ram_total_gib", 0.0), 0),
        "NumHostLoad": fmt(s.get("host_load_mean", 0.0), 0),
    }
    for stage, key in (("init", "Init"), ("environment", "Env"), ("litter + physics", "Phys"),
                       ("clutter", "Clutter"), ("cameras", "Cams"), ("grass", "Grass"),
                       ("render", "Render"), ("write", "Write")):
        macros[f"NumStage{key}"] = fmt(s["stage_mean_s"].get(stage, 0.0), 1)

    lines = [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]

    # Projection table rows: dataset size x GPU count -> hours (cost)
    proj = s["projection"]
    gpu_counts = ["1", "4", "8", "16", "32"]
    rows = []
    for size, by_gpu in proj.items():
        cells = []
        for g in gpu_counts:
            h = by_gpu[g]["hours"]
            cells.append(f"{h:.1f}\\,h" if h < 100 else f"{h / 24:.1f}\\,d")
        cost = by_gpu["1"]["cost"]
        rows.append(f"{int(size) // 1000}\\,k & " + " & ".join(cells) + f" & \\${cost:,.0f}".replace(",", "\\,") + " \\\\")
    lines.append("\\newcommand{\\ProjectionRows}{" + "\n".join(rows) + "}")

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "numbers.tex")
    with open(out, "w", encoding="utf-8") as f:
        f.write("% generated by make_numbers.py - do not edit\n" + "\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
